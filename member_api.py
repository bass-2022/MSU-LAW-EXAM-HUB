@bp.post('/api/members/register')
def register():
    d = request.get_json(silent=True) or {}

    email = str(d.get('email', '')).strip().lower()
    name = str(d.get('displayName', '')).strip()
    student_id = str(d.get('studentId', '')).strip()
    password = str(d.get('password', ''))
    confirm_password = str(d.get('confirmPassword', ''))

    try:
        year_level = int(d.get('yearLevel'))
    except (ValueError, TypeError):
        return jsonify(error='กรุณาเลือกชั้นปี'), 400

    if not (2 <= len(name) <= 80):
        return jsonify(error='กรุณากรอกชื่อ-สกุล 2–80 ตัวอักษร'), 400

    if not re.fullmatch(r'[0-9]{8,15}', student_id):
        return jsonify(error='รหัสนิสิตต้องเป็นตัวเลข 8–15 หลัก'), 400

    if year_level not in (1, 2, 3, 4, 5, 6):
        return jsonify(error='ชั้นปีไม่ถูกต้อง'), 400

    if not re.fullmatch(
        r'[^\s@]{1,100}@[^\s@]{1,100}\.[^\s@]{2,30}',
        email
    ):
        return jsonify(error='รูปแบบอีเมลไม่ถูกต้อง'), 400

    if not (12 <= len(password) <= 256):
        return jsonify(error='รหัสผ่านต้องมีอย่างน้อย 12 ตัวอักษร'), 400

    if password != confirm_password:
        return jsonify(error='รหัสผ่านทั้งสองช่องไม่ตรงกัน'), 400

    salt = secrets.token_hex(16)

    try:
        with _engine.begin() as c:
            c.execute(text('''
                INSERT INTO members (
                    email, display_name, student_id,
                    year_level, password_salt, password_hash
                )
                VALUES (:e, :n, :sid, :year, :s, :h)
            '''), {
                'e': email,
                'n': name,
                'sid': student_id,
                'year': year_level,
                's': salt,
                'h': _hash(password, salt)
            })

    except IntegrityError:
        return jsonify(error='อีเมลนี้ถูกใช้งานแล้ว'), 409

    # ไม่เข้าสู่ระบบอัตโนมัติหลังสมัคร
    return jsonify(
        ok=True,
        message='สมัครสมาชิกสำเร็จ กรุณาเข้าสู่ระบบ'
    ), 201


@bp.post('/api/members/login')
def login():
    d = request.get_json(silent=True) or {}
    email = str(d.get('email', '')).strip().lower()
    password = str(d.get('password', ''))

    if len(email) > 254 or len(password) > 256:
        return jsonify(error='ข้อมูลเข้าสู่ระบบไม่ถูกต้อง'), 400

    with _engine.connect() as c:
        r = c.execute(
            text('SELECT * FROM members WHERE email=:e'),
            {'e': email}
        ).mappings().first()

    salt = r['password_salt'] if r else '00' * 16
    actual = _hash(password, salt)

    if not r or not hmac.compare_digest(actual, r['password_hash']):
        return jsonify(error='อีเมลหรือรหัสผ่านไม่ถูกต้อง'), 401

    session.clear()
    session['member_id'] = r['id']
    session.permanent = True

    return jsonify(ok=True, displayName=r['display_name'])
@bp.post('/api/members/logout')
def logout():
    session.clear()
    return jsonify(ok=True)

@bp.get('/api/members/me')
def me():
    denied=_require()
    if denied:return denied
    with _engine.connect() as c:
        r=c.execute(text('SELECT id,email,display_name,created_at FROM members WHERE id=:id'),{'id':_member_id()}).mappings().first()
    if not r:return jsonify(error='ไม่พบบัญชี'),401
    return jsonify(id=r['id'],email=r['email'],displayName=r['display_name'],createdAt=r['created_at'].isoformat())

@bp.post('/api/members/exams/submit')
def submit_exam():
    denied=_require()
    if denied:return denied
    d=request.get_json(silent=True) or {}
    try:subject_id=int(d.get('subjectId'))
    except (ValueError,TypeError):return jsonify(error='รายวิชาไม่ถูกต้อง'),400
    answers=d.get('answers')
    if not isinstance(answers,dict) or not (1<=len(answers)<=100):
        return jsonify(error='กรุณาส่งคำตอบ 1–100 ข้อ'),400
    try:
        parsed={int(k):int(v) for k,v in answers.items()}
    except (ValueError,TypeError):return jsonify(error='รูปแบบคำตอบไม่ถูกต้อง'),400
    if len(parsed)!=len(answers) or any(q<=0 or v<0 or v>20 for q,v in parsed.items()):
        return jsonify(error='คำตอบไม่ถูกต้อง'),400
    with _engine.begin() as c:
        if not c.execute(text('SELECT 1 FROM subjects WHERE id=:id'),{'id':subject_id}).first():
            return jsonify(error='ไม่พบรายวิชา'),404
        rows=c.execute(text('SELECT id,answer,options FROM questions WHERE subject_id=:sid'),{'sid':subject_id}).mappings().all()
        by_id={r['id']:r for r in rows}
        if not all(q in by_id for q in parsed):
            return jsonify(error='มีข้อสอบที่ไม่อยู่ในรายวิชานี้'),400
        if any(v>=len(json.loads(by_id[q]['options'])) for q,v in parsed.items()):
            return jsonify(error='ตัวเลือกคำตอบไม่ถูกต้อง'),400
        score=sum(v==by_id[q]['answer'] for q,v in parsed.items())
        attempt_id=c.execute(text('''INSERT INTO exam_attempts(member_id,subject_id,score,total)
            VALUES(:mid,:sid,:score,:total) RETURNING id'''),{'mid':_member_id(),'sid':subject_id,'score':score,'total':len(parsed)}).scalar_one()
        for q,v in parsed.items():
            c.execute(text('''INSERT INTO exam_answers(attempt_id,question_id,selected_answer,correct)
              VALUES(:aid,:qid,:v,:correct)'''),{'aid':attempt_id,'qid':q,'v':v,'correct':v==by_id[q]['answer']})
    return jsonify(ok=True,attemptId=attempt_id,score=score,total=len(parsed)),201

@bp.get('/api/members/attempts')
def attempts():
    denied=_require()
    if denied:return denied
    with _engine.connect() as c:
        rows=c.execute(text('''SELECT a.id,a.score,a.total,a.created_at,s.name AS subject_name
           FROM exam_attempts a JOIN subjects s ON s.id=a.subject_id
           WHERE a.member_id=:mid ORDER BY a.created_at DESC,a.id DESC LIMIT 100'''),{'mid':_member_id()}).mappings().all()
    return jsonify([{'id':r['id'],'score':r['score'],'total':r['total'],'subjectName':r['subject_name'],'createdAt':r['created_at'].isoformat()} for r in rows])

@bp.get('/api/members/stats')
def stats():
    denied=_require()
    if denied:return denied
    with _engine.connect() as c:
        r=c.execute(text('''SELECT COUNT(*) AS attempts,COALESCE(SUM(score),0) AS correct,
          COALESCE(SUM(total),0) AS questions,COUNT(DISTINCT subject_id) AS subjects
          FROM exam_attempts WHERE member_id=:mid'''),{'mid':_member_id()}).mappings().one()
    return jsonify(attempts=r['attempts'],subjects=r['subjects'],questions=r['questions'],averagePercent=round(100*r['correct']/r['questions'],1) if r['questions'] else 0)
