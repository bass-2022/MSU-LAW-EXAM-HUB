def _hash(password, salt):
    return hashlib.pbkdf2_hmac('sha256',password.encode('utf-8'),bytes.fromhex(salt),600000).hex()

def _member_id():
    return session.get('member_id')

def _require():
    if not _member_id():
        return jsonify(error='กรุณาเข้าสู่ระบบสมาชิก'),401

def _same_origin():
    # Cookie-authenticated mutations must come from the application's own origin.
    from urllib.parse import urlsplit
    origin = request.headers.get('Origin')
    if origin:
        expected = urlsplit(request.host_url)
        got = urlsplit(origin)
        return (got.scheme,got.netloc)==(expected.scheme,expected.netloc)
    referer = request.headers.get('Referer')
    if referer:
        expected = urlsplit(request.host_url)
        got = urlsplit(referer)
        return (got.scheme,got.netloc)==(expected.scheme,expected.netloc)
    return False

@bp.before_request
def check_origin():
    if request.method in ('POST','PUT','PATCH','DELETE') and not _same_origin():
        return jsonify(error='คำขอไม่ผ่านการตรวจสอบต้นทาง'),403

