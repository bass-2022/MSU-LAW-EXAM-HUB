def fetchone(sql, params=None):
    with engine.connect() as c:
        row = c.execute(text(sql), params or {}).mappings().first()
        return dict(row) if row is not None else None

def fetchall(sql, params=None):
    with engine.connect() as c:
        return [dict(row) for row in c.execute(text(sql), params or {}).mappings().all()]

def execute(sql, params=None):
    with engine.begin() as c:
        result = c.execute(text(sql), params or {})
        return result.rowcount

def hashpw(password, salt):
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), 600000).hex()

def bootstrap_admin():
    username = os.environ.get("MSU_ADMIN_USERNAME", "").strip()
    password = os.environ.get("MSU_ADMIN_PASSWORD", "")
    if not username and not password:
        return
    if not username or len(password) < 12:
        raise RuntimeError("Set MSU_ADMIN_USERNAME and MSU_ADMIN_PASSWORD (at least 12 characters)")
    salt = secrets.token_hex(16)
    with engine.begin() as c:
        c.execute(text("""
            INSERT INTO admins(username,salt,password_hash)
            VALUES (:u,:s,:h) ON CONFLICT (username) DO NOTHING
        """), {"u": username, "s": salt, "h": hashpw(password, salt)})

